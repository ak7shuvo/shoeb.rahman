import os, asyncio, re
from playwright.async_api import async_playwright
B = os.environ.get("BASE", "http://localhost:3000")
res = []
def ok(name, cond, detail=""): res.append(("PASS" if cond else "FAIL", name, str(detail)[:140]))
VIS = "(sel)=>[...document.querySelectorAll(sel)].filter(e=>!e.closest('[hidden]')).length"

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        # ---- mobile menu
        ctx = await b.new_context(viewport={"width": 390, "height": 844}); pg = await ctx.new_page()
        await pg.goto(B + "/about", wait_until="networkidle")
        await pg.click(".menu-btn"); await pg.wait_for_selector("#site-sheet")
        ok("menu: focus moves into sheet", "Home" in await pg.evaluate("document.activeElement.textContent"))
        ok("menu: page behind inert", await pg.evaluate("document.querySelector('main').hasAttribute('inert')"))
        ok("menu: current page marked", await pg.evaluate("document.querySelector('#site-sheet [aria-current=page]')?.textContent.includes('About')"))
        for _ in range(14): await pg.keyboard.press("Tab")
        ok("menu: Tab contained", await pg.evaluate("!!document.activeElement.closest('#site-sheet,.menu-btn')"))
        await pg.keyboard.press("Escape")
        ok("menu: Esc closes, focus to toggle", await pg.evaluate("!document.querySelector('#site-sheet') && document.activeElement.classList.contains('menu-btn')"))
        await pg.click(".menu-btn"); await pg.click("#site-sheet a[href='/locations']"); await pg.wait_for_url("**/locations"); await pg.wait_for_timeout(400)
        ok("menu: link navigates and closes", await pg.evaluate("!document.querySelector('#site-sheet') && location.pathname==='/locations'"))
        await pg.click(".menu-btn"); await pg.set_viewport_size({"width": 1300, "height": 900}); await pg.wait_for_timeout(300)
        ok("menu: closes on resize to desktop", await pg.evaluate("!document.querySelector('#site-sheet')"))
        await ctx.close()

        # ---- theme, skip link, header, back-to-top, client nav
        ctx = await b.new_context(viewport={"width": 1440, "height": 900}); pg = await ctx.new_page()
        await pg.goto(B + "/", wait_until="networkidle")
        await pg.keyboard.press("Tab")
        ok("skip link is first Tab stop", await pg.evaluate("document.activeElement.classList.contains('skip')"))
        await pg.keyboard.press("Enter"); await pg.wait_for_timeout(200)
        ok("skip link focuses main", await pg.evaluate("document.activeElement.id==='main'"))
        before = await pg.evaluate("getComputedStyle(document.body).backgroundColor")
        await pg.click(".bar .icon-btn"); await pg.wait_for_timeout(450)
        after = await pg.evaluate("getComputedStyle(document.body).backgroundColor")
        lbl = await pg.get_attribute(".bar .icon-btn", "aria-label")
        ok("theme toggle switches to dark", await pg.evaluate("document.documentElement.dataset.theme") == "dark" and before != after and "light" in lbl, f"{before} -> {after} / {lbl}")
        await pg.reload(wait_until="networkidle")
        ok("theme choice persists across reload", await pg.evaluate("document.documentElement.dataset.theme") == "dark")
        await pg.click(".bar .icon-btn"); await pg.wait_for_timeout(200)
        ok("theme toggles back to light", await pg.evaluate("document.documentElement.dataset.theme") == "light")
        y0 = await pg.evaluate("document.querySelector('.hero').getBoundingClientRect().top+scrollY")
        await pg.mouse.wheel(0, 700); await pg.wait_for_timeout(500)
        y1 = await pg.evaluate("document.querySelector('.hero').getBoundingClientRect().top+scrollY")
        ok("header gains scrolled state with no layout shift", await pg.evaluate("document.querySelector('.bar').classList.contains('is-scrolled')") and abs(y0 - y1) < 1, f"{y0} {y1}")
        await pg.evaluate("window.scrollTo({top:4000,behavior:'instant'})"); await pg.wait_for_timeout(500)
        prog = await pg.evaluate("document.querySelector('.to-top').style.getPropertyValue('--scroll')")
        ok("back-to-top appears with progress", await pg.evaluate("document.querySelector('.to-top').classList.contains('is-on')") and float(prog or 0) > 0, prog)
        await pg.click(".to-top"); await pg.wait_for_timeout(1500)
        ok("back-to-top returns to top and focuses main", await pg.evaluate("scrollY<5 && document.activeElement.id==='main'"))
        await pg.click(".nav a[href='/research']"); await pg.wait_for_url("**/research"); await pg.mouse.wheel(0, 900); await pg.wait_for_timeout(900)
        ok("client navigation: active nav + reveals run", await pg.evaluate("document.querySelector('.nav a[aria-current=page]')?.getAttribute('href')==='/research' && document.querySelectorAll('[data-reveal].is-in').length>3"))
        # concept map → filtered archive
        await pg.goto(B + "/research#map", wait_until="networkidle"); await pg.wait_for_timeout(500)
        await pg.click(".cmap a.node.pillar:has-text('GOVERNANCE')"); await pg.wait_for_url("**/publications?theme=governance"); await pg.wait_for_timeout(700)
        st = await pg.evaluate("document.querySelector('.result-bar [role=status]').textContent")
        ok("concept map node opens filtered archive", "Showing 6 of 28" in st, st)
        await ctx.close()

        # ---- publications explorer
        ctx = await b.new_context(viewport={"width": 1440, "height": 900}, permissions=["clipboard-read", "clipboard-write"]); pg = await ctx.new_page()
        await pg.goto(B + "/publications", wait_until="networkidle")
        stat = lambda: pg.evaluate("document.querySelector('.result-bar [role=status]').textContent")
        ok("archive lists all outputs", "Showing 28 of 28" in await stat())
        await pg.fill("input[type=search]", "Sundarbans"); await pg.wait_for_timeout(300)
        ok("search 'Sundarbans' → 2", "Showing 2 of 28" in await stat() and "q=Sundarbans" in pg.url, await stat())
        await pg.fill("input[type=search]", "zzzz"); await pg.wait_for_timeout(300)
        ok("empty state shown", await pg.evaluate("!!document.querySelector('.empty')"))
        await pg.click(".empty button"); await pg.wait_for_timeout(300)
        ok("clear filters restores all", "Showing 28 of 28" in await stat() and "q=" not in pg.url)
        await pg.click("button.chip:has-text('Book chapters')"); await pg.wait_for_timeout(700)
        vis_ok = await pg.evaluate("[...document.querySelectorAll('.year-group:not([hidden]) > div:not([hidden])')].every(d=>parseFloat(getComputedStyle(d).opacity)>0.99)")
        ok("type chip 'Book chapters' → 5, visible", "Showing 5 of 28" in await stat() and vis_ok and "type=chapter" in pg.url, await stat())
        await pg.select_option("select >> nth=0", "technology"); await pg.wait_for_timeout(300)
        ok("type + theme combine (chapters ∩ technology → 1)", "Showing 1 of 28" in await stat(), await stat())
        await pg.reload(wait_until="networkidle"); await pg.wait_for_timeout(500)
        ok("filters restored from URL on reload", "Showing 1 of 28" in await stat() and await pg.evaluate("document.querySelector('select').value") == "technology")
        await pg.goto(B + "/publications?place=rural&sort=old", wait_until="networkidle"); await pg.wait_for_timeout(400)
        first = await pg.evaluate("document.querySelector('.year-group:not([hidden]) .year-head').firstChild.textContent")
        ok("deep link place=rural&sort=old → 3, oldest first", "Showing 3 of 28" in await stat() and first == "2018", f"{await stat()} first={first}")
        await pg.goto(B + "/publications", wait_until="networkidle")
        await pg.click("#governing-fragility .copy"); await pg.wait_for_timeout(300)
        clip = await pg.evaluate("navigator.clipboard.readText()")
        ok("copy reference writes full reference", clip.startswith("Md Ariful Hoque, Abrar Faisal, Easnin Ara & Muhammad Shoeb-Ur-Rahman (2026). Governing fragility") and clip.endswith("https://doi.org/10.1080/02508281.2026.2690977"), clip)
        ok("copy feedback announced", "Copied" in await pg.evaluate("document.querySelector('#governing-fragility .copy').textContent"))
        ok("2026 group ordered by online date", await pg.evaluate("[...document.querySelectorAll('#y-2026 ~ div article')].map(a=>a.id).join(',')") == "governing-fragility,governance-trembles,beyond-survival")
        await ctx.close()

        # ---- locations
        ctx = await b.new_context(viewport={"width": 1440, "height": 900}); pg = await ctx.new_page()
        await pg.goto(B + "/locations", wait_until="networkidle")
        await pg.click(".marker[aria-label^='Sundarbans']"); await pg.wait_for_timeout(300)
        ok("map marker selects place (panel + URL)", await pg.evaluate("document.querySelector('.place-btn[aria-pressed=true]').textContent.includes('Sundarbans')") and "place=sundarbans" in pg.url and await pg.evaluate(VIS, ".place-panel .mini-pub") == 2)
        await pg.focus(".marker[aria-label^='Dhaka']"); await pg.keyboard.press("Enter"); await pg.wait_for_timeout(300)
        ok("marker is keyboard operable", "place=dhaka" in pg.url)
        await pg.goto(B + "/locations?place=stmartin", wait_until="networkidle"); await pg.wait_for_timeout(300)
        ok("deep link selects St. Martin's", await pg.evaluate("document.querySelector('.place-btn[aria-pressed=true]').textContent.includes('Martin')"))
        # journey details
        await pg.goto(B + "/journey", wait_until="networkidle")
        await pg.click("details.more summary >> nth=0"); await pg.wait_for_timeout(200)
        ok("course list expands", await pg.evaluate("document.querySelector('details.more').open"))
        await ctx.close()

        # ---- contact copy email
        ctx = await b.new_context(viewport={"width": 1440, "height": 900}, permissions=["clipboard-read", "clipboard-write"]); pg = await ctx.new_page()
        await pg.goto(B + "/contact", wait_until="networkidle")
        await pg.click(".contact-hero .copy"); await pg.wait_for_timeout(300)
        ok("copy email address", await pg.evaluate("navigator.clipboard.readText()") == "shoeb.rahman@du.ac.bd")
        ok("external links are safe", await pg.evaluate("[...document.querySelectorAll('a[target=_blank]')].every(a=>a.rel.includes('noopener'))"))
        await ctx.close()

        # ---- reduced motion / JS failure
        ctx = await b.new_context(viewport={"width": 1440, "height": 900}, reduced_motion="reduce"); pg = await ctx.new_page()
        await pg.goto(B + "/", wait_until="networkidle"); await pg.wait_for_timeout(400)
        ok("reduced motion: nothing hidden", await pg.evaluate("[...document.querySelectorAll('[data-reveal]')].filter(e=>parseFloat(getComputedStyle(e).opacity)<0.99).length") == 0)
        await ctx.close()
        ctx = await b.new_context(viewport={"width": 1440, "height": 900}); pg = await ctx.new_page()
        await pg.route("**/_next/static/chunks/**", lambda r: r.abort())
        await pg.goto(B + "/publications", wait_until="load"); await pg.wait_for_timeout(3000)
        hidden = await pg.evaluate("[...document.querySelectorAll('[data-reveal]')].filter(e=>parseFloat(getComputedStyle(e).opacity)<0.99).length")
        n = await pg.evaluate("document.querySelectorAll('article.pub').length")
        ok("JS blocked: content visible and all 28 records in HTML", hidden == 0 and n == 28, f"hidden={hidden} records={n}")
        await ctx.close()

        # ---- links & assets
        ctx = await b.new_context(); pg = await ctx.new_page(); seen = set(); bad = []
        for r in ["/", "/research", "/publications", "/books", "/projects", "/locations", "/journey", "/about", "/contact"]:
            await pg.goto(B + r, wait_until="networkidle")
            for h in await pg.evaluate("[...document.querySelectorAll('a[href]')].map(a=>a.getAttribute('href'))"):
                if h.startswith("/") and h not in seen:
                    seen.add(h); path, _, frag = h.partition("#")
                    resp = await pg.request.get(B + path)
                    if resp.status != 200: bad.append((h, resp.status))
                    elif frag and f'id="{frag}"' not in await resp.text(): bad.append((h, "missing anchor"))
                elif h.startswith("#") and h != "#main" and not await pg.evaluate(f"!!document.getElementById('{h[1:]}')"): bad.append((r + h, "missing anchor"))
        for a in ["/robots.txt", "/sitemap.xml", "/manifest.webmanifest", "/og-image.png", "/icon.svg", "/favicon.ico", "/apple-icon.png", "/icon-192.png", "/icon-512.png", "/topo.svg", "/fonts/source-serif-4-latin-ext-wght-normal.woff2", "/images/portrait/portrait.jpg"]:
            resp = await pg.request.get(B + a)
            if resp.status != 200: bad.append((a, resp.status))
        ok("internal links, anchors and assets resolve", not bad, f"{len(seen)} links; bad={bad}")
        ok("unknown route returns 404", (await pg.request.get(B + "/nope")).status == 404)
        await ctx.close(); await b.close()
    for r in res: print(*r)
    print("pass", sum(1 for r in res if r[0] == "PASS"), "/", len(res))
asyncio.run(main())
